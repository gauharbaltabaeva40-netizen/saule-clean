const languageButtons = [...document.querySelectorAll("[data-language]")];
const translatedNodes = [...document.querySelectorAll("[data-i18n]")];
const translatedAlts = [...document.querySelectorAll("[data-i18n-alt]")];
const whatsappLinks = [...document.querySelectorAll("[data-whatsapp]")];
const nav = document.querySelector("#main-nav");
const menuToggle = document.querySelector(".menu-toggle");

function setLanguage(language) {
  const selected = copy[language] ? language : "ru";
  document.documentElement.lang = selected === "kk" ? "kk" : "ru";
  translatedNodes.forEach((node) => {
    const value = copy[selected][node.dataset.i18n];
    if (value) node.innerHTML = value;
  });
  translatedAlts.forEach((node) => {
    const value = copy[selected][node.dataset.i18nAlt];
    if (value) node.alt = value;
  });
  languageButtons.forEach((button) => {
    const active = button.dataset.language === selected;
    button.classList.toggle("is-active", active);
    button.setAttribute("aria-pressed", String(active));
  });
  whatsappLinks.forEach((link) => {
    link.href = `https://wa.me/77782867311?text=${encodeURIComponent(copy[selected].whatsappMessage)}`;
    link.setAttribute("aria-label", selected === "kk" ? "Taza-Nur компаниясына WhatsApp арқылы жазу" : "Написать Taza-Nur в WhatsApp");
  });
  document.title = selected === "kk" ? "Taza-Nur — Астанадағы клининг" : "Taza-Nur — клининг в Астане";
  try { localStorage.setItem("taza-nur-language", selected); } catch {}
}

languageButtons.forEach((button) => button.addEventListener("click", () => setLanguage(button.dataset.language)));
menuToggle?.addEventListener("click", () => {
  const isOpen = nav.classList.toggle("is-open");
  menuToggle.setAttribute("aria-expanded", String(isOpen));
  menuToggle.setAttribute("aria-label", isOpen ? "Закрыть меню" : "Открыть меню");
});
nav?.querySelectorAll("a").forEach((link) => link.addEventListener("click", () => {
  nav.classList.remove("is-open");
  menuToggle?.setAttribute("aria-expanded", "false");
}));
document.querySelector("#current-year").textContent = String(new Date().getFullYear());
let savedLanguage = "ru";
try { savedLanguage = localStorage.getItem("taza-nur-language") || "ru"; } catch {}
setLanguage(savedLanguage);
